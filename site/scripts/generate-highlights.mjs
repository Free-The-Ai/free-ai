import { writeFile } from "node:fs/promises";
import { codeToHtml } from "shiki";
import { homeSnippet, docsSnippets, quickstartSnippets } from "../src/shared/config/codeSnippets.ts";
import { SETUP_GUIDES } from "../src/entities/setup-guide/model.ts";

const languages = {
    bash: "bash",
    javascript: "javascript",
    typescript: "typescript",
    python: "python",
    json: "json",
    yaml: "yaml",
    text: "text",
    plaintext: "text",
    curl: "bash",
    shell: "bash",
};

const stripPreBackground = {
    name: "strip-pre-background",
    pre(node) {
        if (typeof node.properties?.style === "string") {
            node.properties.style = node.properties.style.replace(/background-color\s*:[^;]+;?/gi, "").trim();
        }
    },
};

async function highlight(code, lang) {
    return codeToHtml(code, {
        lang: languages[lang] ?? "text",
        theme: "dark-plus",
        transformers: [stripPreBackground],
    });
}

const highlighted = {
    home: await highlight(homeSnippet, "bash"),
    docs: {
        base: await highlight(docsSnippets.base, "bash"),
        chatCurl: await highlight(docsSnippets.chatCurl, "bash"),
        openAiSdk: await highlight(docsSnippets.openAiSdk, "javascript"),
        messages: await highlight(docsSnippets.messages, "bash"),
        modelList: await highlight(docsSnippets.modelList, "bash"),
        fullModelList: await highlight(docsSnippets.fullModelList, "bash"),
    },
    quickstart: {
        python: await highlight(quickstartSnippets.python, "python"),
        javascript: await highlight(quickstartSnippets.javascript, "typescript"),
        curl: await highlight(quickstartSnippets.curl, "bash"),
    },
    setup: Object.fromEntries(
        await Promise.all(
            SETUP_GUIDES.map(async (guide) => [
                guide.slug,
                await Promise.all(guide.steps.map((step) => (step.code ? highlight(step.code.value, step.code.lang) : null))),
            ]),
        ),
    ),
};

const output = `// Generated by scripts/generate-highlights.mjs. Do not edit.\nexport const highlightedCode = ${JSON.stringify(highlighted)} as const;\n`;
await writeFile(new URL("../src/shared/config/highlighted.generated.ts", import.meta.url), output, "utf8");
